export function theoryPanel(chapter, escape) {
  const theory = waterTheory[chapter];
  if (!theory) return '';
  const [question, answer] = theory.example;

  return `<details class="quest-theory">
    <summary>📚 Uitleg &amp; theorie</summary>
    <div class="theory-content">
      <h2>${escape(theory.title)}</h2>
      <div class="theory-topics">
        ${theory.topics.map(([title, body]) => `<section><h3>${escape(title)}</h3><p>${escape(body)}</p></section>`).join('')}
      </div>
      <h3>Kernbegrippen</h3>
      <dl class="theory-terms">
        ${theory.terms.map(([term, meaning]) => `<div><dt>${escape(term)}</dt><dd>${escape(meaning)}</dd></div>`).join('')}
      </dl>
      <section class="theory-example">
        <h3>Uitgewerkt voorbeeld</h3>
        <p><strong>${escape(question)}</strong></p>
        <p>${escape(answer)}</p>
        <p class="small muted">Noem de oorzaak, beschrijf wat er verandert en geef het gevolg.</p>
      </section>
      <p class="small muted">Gebaseerd op De Geo 4 vmbo-kgt · Water · ${chapter}</p>
    </div>
  </details>`;
}
